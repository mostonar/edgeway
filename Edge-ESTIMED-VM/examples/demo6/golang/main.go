/**
 * @brief Extracts subscription ID from a subscription URL
 *
 * This utility function parses a subscription URL to extract the subscription ID
 * using regular expressions. It matches the subscription ID pattern from the URL
 * and returns the extracted identifier.
 *
 * @param base_url The base URL for the subscription endpoint
 * @param subscription_url The complete subscription URL containing the ID
 * @return string The extracted subscription ID
 * @return error Error if URL parsing or regex matching fails
 */
func extract_subscription_id(base_url string, subscription_url string) (string, error) {
	fmt.Println(">>> extract_subscription_id: base_url: " + base_url)
	fmt.Println(">>> extract_subscription_id: subscription_url: " + subscription_url)

	u, _ := url.Parse(base_url)
	fmt.Println("extract_subscription_id: subscription_url: " + u.RequestURI())
	re := regexp.MustCompile(u.RequestURI() + "/(?P<sub_id>.+)")
	if re == nil {
		return "", errors.New("Regexp creation failure")
	}
	matches := re.FindStringSubmatch(subscription_url)
	if matches == nil {
		return "", errors.New("Matching failure")
	}

	return matches[re.SubexpIndex("sub_id")], nil
}


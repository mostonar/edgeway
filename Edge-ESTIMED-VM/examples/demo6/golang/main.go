/**
 * @brief Performs logout from the MEC sandbox system
 *
 * This function performs a complete cleanup of the current session by:
 * - Deleting all active subscriptions
 * - Deleting termination subscriptions
 * - Deleting MEC services
 * - Deregistering the application
 * - Deleting application instances
 * - Terminating active scenarios
 * - Logging out from the sandbox
 *
 * @return error Error if logout fails or if no active session exists
 */
func logout() error {
	fmt.Println(">>> logout: ", sandboxName)

	// Sanity check
	if sandboxName == "" {
		err := errors.New("logout: Wrong parameters")
		return err
	}

	// Delete subscriptions done
	if len(subscriptions) != 0 {
		for _, l := range subscriptions {
			delete_subscription(l.Href)
		} // End of 'for' statement
	}

	// Delete subscription if any
	if terminationSubscriptionID != "" {
		delete_termination_subscription()
	}

	// Delete MEC service if any
	if appServiceInfo.SerInstanceId != "" {
		mec011_delete_service()
	}

	// Delete registration if any
	if isRegistered {
		mec011_send_deregistration()
	}

	// Delete created AppInstId if any
	if appsInfo.Id != "" {
		deleteMECAppInstId()
		appsInfo.Id = ""
		time.Sleep(2 * time.Second)
	}

	if appServiceInfo.SerInstanceId != "" {
		mec011_delete_service()
		appServiceInfo.SerInstanceId = ""
		time.Sleep(2 * time.Second)
	}

	// Terminate scenario if any
	if scenarioId != -1 {
		terminateScenario(scenarios[scenarioId].Id)
		scenarioId = -1
		time.Sleep(2 * time.Second)
	}

	_, err := cl.AuthorizationApi.Logout(context.TODO(), sandboxName)
	if err != nil {
		return err
	}

	sandboxName = ""

	return nil
}


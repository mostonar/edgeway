/**
 * @brief Sends HTTP requests to MEC services with proper authentication and headers
 *
 * This utility function handles HTTP communication with MEC services, including
 * request preparation, authentication, and response handling. It supports various
 * HTTP methods and query parameters.
 *
 * @param method HTTP method (GET, POST, DELETE, etc.)
 * @param path URL path for the request
 * @param body Request body for POST/PUT operations
 * @param vars URL variables for path substitution
 * @param queryParams Query parameters to append to the URL
 * @param location Optional location header for redirects
 * @return []byte Response body from the service
 * @return *http.Response Complete HTTP response
 * @return error Error if the request fails or prerequisites are not met
 */
func send_mec_service_request(method string, path string, body io.Reader, vars url.Values, queryParams url.Values, location *string) (resbody []byte, res *http.Response, err error) {
	fmt.Println(">>> send_mec_service_request: ", appsInfo.Name)

	// Sanity checks
	if sandboxName == "" {
		err = errors.New("No sandbox available")
		return nil, nil, err
	} else if scenarioId == -1 {
		return nil, nil, errors.New("No network scenario available")
	}

	// Setup path and query parameters
	url, err := url.Parse(path)
	if err != nil {
		return nil, nil, err
	}

	// Adding Query Param
	query := url.Query()
	for k, v := range queryParams {
		for _, iv := range v {
			query.Add(k, iv)
		}
	}

	// Encode the parameters.
	url.RawQuery = query.Encode()

	// Generate a new request
	var localVarRequest *http.Request
	if body != nil {
		localVarRequest, err = http.NewRequest(method, url.String(), body)
	} else {
		localVarRequest, err = http.NewRequest(method, url.String(), nil)
	}
	if err != nil {
		return nil, nil, err
	}

	// Override request host, if applicable
	if cfg.Host != "" {
		localVarRequest.Host = cfg.Host
	}

	headers := http.Header{}
	headers.Set("Accept", "application/json")
	localVarRequest.Header = headers

	// Add the user agent to the request.
	localVarRequest.Header.Add("User-Agent", cfg.UserAgent)

	//fmt.Println("send_mec_service_request: localVarRequest: ", localVarRequest)

	// tr := &http.Transport{
	// 	TLSClientConfig: &tls.Config{InsecureSkipVerify: true},
	// }
	// cfg.HTTPClient = &http.Client{Transport: tr}

	res, err = cfg.HTTPClient.Do(localVarRequest)
	if err != nil {
		return nil, nil, err
	}

	resbody, err = ioutil.ReadAll(res.Body)
	if err != nil {
		return nil, nil, err
	}
	res.Body.Close()

	return resbody, res, err
}

